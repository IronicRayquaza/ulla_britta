#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { capabilityMap } from '../src/agent/tools/index.mjs';

/**
 * Regenerates the tool inventory inside docs/AGENT_CAPABILITIES.md.
 *
 * A capability list maintained by hand is a capability list that is wrong within a
 * fortnight — which is how the agent ended up telling a user it could not read a
 * profile while nobody noticed the gap. The prose around it is written by people;
 * the table between the markers is read off the registry, and a test fails if the
 * file on disk does not match what this produces.
 *
 *   node scripts/generate-capability-docs.mjs          write
 *   node scripts/generate-capability-docs.mjs --check  verify only
 */

const here = path.dirname(fileURLToPath(import.meta.url));
const DOC = path.join(here, '..', 'docs', 'AGENT_CAPABILITIES.md');

const BEGIN = '<!-- BEGIN GENERATED: tool inventory -->';
const END = '<!-- END GENERATED: tool inventory -->';

const TITLES = {
    repositories: 'Repositories',
    files: 'Files and code',
    git: 'Branches, commits and history',
    issues: 'Issues, labels and milestones',
    pullRequests: 'Pull requests',
    actions: 'GitHub Actions and CI',
    releases: 'Releases',
    users: 'People and accounts',
    insights: 'Insight, discovery and delivery'
};

/** Tools that cannot work with the app's installation token alone. */
const USER_SCOPED = new Set([
    'star_repository', 'unstar_repository', 'follow_user', 'unfollow_user',
    'list_notifications', 'mark_notifications_read', 'create_gist'
]);

const escape = (s) => String(s).replace(/\|/g, '\\|');

function marks(tool) {
    const flags = [];
    if (tool.destructive) flags.push('**destructive**');
    else if (tool.sideEffecting) flags.push('writes');
    if (USER_SCOPED.has(tool.name)) flags.push('needs user auth');
    return flags.join(', ') || 'read-only';
}

function args(tool) {
    if (!tool.parameters.length) return '—';
    return tool.parameters
        .map(p => (tool.required.includes(p) ? `\`${p}\`*` : `\`${p}\``))
        .join(', ');
}

export function render() {
    const domains = capabilityMap();
    const total = domains.reduce((n, d) => n + d.count, 0);

    const lines = [
        BEGIN,
        '',
        `**${total} tools across ${domains.length} domains.** Arguments marked \`*\` are required.`,
        '',
        '| Domain | Tools |',
        '| --- | ---: |',
        ...domains.map(d => `| [${TITLES[d.domain] || d.domain}](#${(TITLES[d.domain] || d.domain).toLowerCase().replace(/[^a-z0-9]+/g, '-')}) | ${d.count} |`),
        `| **Total** | **${total}** |`,
        ''
    ];

    for (const domain of domains) {
        lines.push(`### ${TITLES[domain.domain] || domain.domain}`, '');
        lines.push('| Tool | Does | Arguments | |');
        lines.push('| --- | --- | --- | --- |');
        for (const tool of domain.tools) {
            lines.push(`| \`${tool.name}\` | ${escape(tool.description)} | ${args(tool)} | ${marks(tool)} |`);
        }
        lines.push('');
    }

    lines.push(
        '_This section is generated by `npm run docs:capabilities`. Edit the tools, not the table._',
        '',
        END
    );

    return lines.join('\n');
}

/** Splices the generated block into the document, leaving the prose alone. */
export function splice(document) {
    const start = document.indexOf(BEGIN);
    const end = document.indexOf(END);
    if (start === -1 || end === -1) {
        throw new Error(`${DOC} is missing the generated-block markers.`);
    }
    return document.slice(0, start) + render() + document.slice(end + END.length);
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('generate-capability-docs.mjs')) {
    const current = fs.readFileSync(DOC, 'utf8');
    const updated = splice(current);

    if (process.argv.includes('--check')) {
        if (current !== updated) {
            console.error('❌ docs/AGENT_CAPABILITIES.md is out of date. Run: npm run docs:capabilities');
            process.exit(1);
        }
        console.log('✅ docs/AGENT_CAPABILITIES.md matches the registry.');
    } else {
        fs.writeFileSync(DOC, updated);
        console.log('✅ Wrote docs/AGENT_CAPABILITIES.md');
    }
}
